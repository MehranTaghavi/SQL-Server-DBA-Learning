-- ================================================================
-- 📘 تمرین ۱۹-۶: استفاده از CASE WHEN در ORDER BY
-- ================================================================
-- 
-- 🎯 هدف تمرین:
-- مرتب‌سازی سفارشی کارمندان بر اساس اولویت بخش‌ها
-- با استفاده از CASE WHEN در ORDER BY
--
-- 📚 مفاهیم کلیدی:
-- 1. استفاده از CASE WHEN برای مرتب‌سازی غیرعادی
-- 2. اولویت‌بندی دسته‌های مختلف
-- 3. ترکیب ORDER BY با CASE WHEN و سایر ستون‌ها
--
-- 📋 اولویت بخش‌ها:
-- 🥇 اولویت ۱: IT
-- 🥈 اولویت ۲: HR
-- 🥉 اولویت ۳: Sales
--
-- 🔍 نحوه کار:
-- 1. CASE WHEN به هر بخش یک عدد اولویت اختصاص می‌دهد
-- 2. ORDER BY ابتدا بر اساس این اولویت مرتب می‌کند
-- 3. سپس در هر بخش، بر اساس حقوق (از بالا به پایین) مرتب می‌کند
-- ================================================================

SELECT 
    FirstName,
    LastName,
    Department,
    Salary,
    -- 📊 نمایش اولویت اختصاص داده شده به هر بخش (اختیاری برای درک بهتر)
    CASE Department
        WHEN 'IT' THEN 1
        WHEN 'HR' THEN 2
        WHEN 'Sales' THEN 3
        ELSE 4
    END as SortOrder
FROM Employees
-- 📊 مرتب‌سازی اصلی:
-- 1. ابتدا بر اساس اولویت بخش (IT → HR → Sales)
-- 2. سپس در هر بخش، بر اساس حقوق (بیشترین به کمترین)
ORDER BY 
    CASE Department
        WHEN 'IT' THEN 1
        WHEN 'HR' THEN 2
        WHEN 'Sales' THEN 3
        ELSE 4
    END,
    Salary DESC;

