-- ================================================================
-- 📘 تمرین ۱۹-۲: ترجمه نام بخش‌ها با CASE WHEN
-- ================================================================
-- 
-- 🎯 هدف تمرین:
-- نمایش نام بخش‌های شرکت به زبان فارسی با استفاده از CASE WHEN
--
-- 📚 مفاهیم کلیدی:
-- 1. CASE WHEN ساده (مقایسه یک ستون با مقادیر مختلف)
-- 2. ترجمه و محلی‌سازی داده‌ها
-- 3. ساختار ساده‌تر CASE WHEN برای مقایسه با یک ستون
--
-- 🏗️ ساختار CASE WHEN ساده:
-- CASE ColumnName
--     WHEN مقدار_۱ THEN نتیجه_۱
--     WHEN مقدار_۲ THEN نتیجه_۲
--     ELSE نتیجه_پیش‌فرض
-- END
--
-- 🔍 تفاوت با نوع قبلی:
-- نوع قبلی: CASE WHEN شرط THEN مقدار
-- این نوع:  CASE ستون WHEN مقدار THEN مقدار
-- ================================================================

SELECT 
    FirstName,
    LastName,
    Department,
    -- 📊 ترجمه نام بخش به فارسی
    CASE Department
        WHEN 'IT' THEN 'فناوری اطلاعات'
        WHEN 'Sales' THEN 'فروش'
        WHEN 'HR' THEN 'منابع انسانی'
        ELSE 'سایر'  -- اگر بخش دیگری وجود داشته باشد
    END as DepartmentName,
    Salary
FROM Employees
ORDER BY Department;

